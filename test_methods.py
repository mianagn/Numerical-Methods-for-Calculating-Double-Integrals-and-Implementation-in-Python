#!/usr/bin/env python
"""
Σενάριο δοκιμών για την επαλήθευση των υλοποιήσεων αριθμητικής ολοκλήρωσης.

Κάθε δοκιμή συγκρίνει το αποτέλεσμα της μεθόδου με την ΑΚΡΙΒΗ αναλυτική τιμή
του ολοκληρώματος και ελέγχει ότι το σφάλμα είναι μικρότερο από ένα κατώφλι.
"""

import sys
import numpy as np

# Προσθήκη του φακέλου code στη διαδρομή αναζήτησης modules
sys.path.insert(0, 'code')

from simpsons_rule import SimpsonsRule1D, SimpsonsRule2D
from quadrature_methods import GaussianQuadrature, TrapezoidalRule, MidpointRule

# Μετρητές επιτυχημένων / αποτυχημένων δοκιμών
apotelesmata = []


def elegxos(onoma, timi, akrivis, katofli):
    """Συγκρίνει την υπολογισμένη τιμή με την ακριβή και καταγράφει το αποτέλεσμα."""
    sfalma = abs(timi - akrivis)
    petyxe = sfalma < katofli
    apotelesmata.append(petyxe)
    print(f"Ακριβής τιμή:      {akrivis:.10f}")
    print(f"Υπολογισμένη τιμή: {timi:.10f}")
    print(f"Σφάλμα:            {sfalma:.2e}   (κατώφλι: {katofli:.0e})")
    print("[OK]  " + onoma if petyxe else "[FAIL] " + onoma)
    return petyxe


print("=" * 70)
print("ΔΟΚΙΜΕΣ ΜΕΘΟΔΩΝ ΑΡΙΘΜΗΤΙΚΗΣ ΟΛΟΚΛΗΡΩΣΗΣ")
print("=" * 70)

# --------------------------------------------------------------------------
# ΔΟΚΙΜΗ 1: Σύνθετος Simpson στη συνάρτηση x²
# Ο Simpson είναι ακριβής για πολυώνυμα έως 3ου βαθμού, άρα περιμένουμε
# σφάλμα στο επίπεδο του σφάλματος στρογγυλοποίησης.
# --------------------------------------------------------------------------
print("\n[ΔΟΚΙΜΗ 1] Σύνθετος Simpson: ∫₀² x² dx = 8/3")
print("-" * 70)

def f1(x):
    return x**2

elegxos("Δοκιμή 1", SimpsonsRule1D.composite(f1, 0, 2, n=10), 8/3, 1e-12)

# --------------------------------------------------------------------------
# ΔΟΚΙΜΗ 2: Ολοκλήρωση Gauss στη συνάρτηση sin(x)
# --------------------------------------------------------------------------
print("\n[ΔΟΚΙΜΗ 2] Gaussian Quadrature: ∫₀^π sin(x) dx = 2")
print("-" * 70)

def f2(x):
    return np.sin(x)

elegxos("Δοκιμή 2", GaussianQuadrature.integrate(f2, 0, np.pi, n=5), 2.0, 1e-6)

# --------------------------------------------------------------------------
# ΔΟΚΙΜΗ 3: Simpson σε δύο διαστάσεις
# --------------------------------------------------------------------------
print("\n[ΔΟΚΙΜΗ 3] Simpson 2D: ∫∫[0,1]×[0,1] xy dy dx = 1/4")
print("-" * 70)

def f3(x, y):
    return x * y

elegxos("Δοκιμή 3", SimpsonsRule2D.composite(f3, 0, 1, 0, 1, nx=10, ny=10), 0.25, 1e-12)

# --------------------------------------------------------------------------
# ΔΟΚΙΜΗ 4: Ολοκλήρωση Gauss σε δύο διαστάσεις
# Με n=3 κόμβους ανά διεύθυνση η μέθοδος είναι ακριβής για πολυώνυμα
# βαθμού έως 5 σε κάθε μεταβλητή, άρα το xy υπολογίζεται ακριβώς.
# --------------------------------------------------------------------------
print("\n[ΔΟΚΙΜΗ 4] Gaussian Quadrature 2D: ∫∫[0,1]×[0,1] xy dy dx = 1/4")
print("-" * 70)

elegxos("Δοκιμή 4", GaussianQuadrature.integrate_2d(f3, 0, 1, 0, 1, n=3), 0.25, 1e-12)

# --------------------------------------------------------------------------
# ΔΟΚΙΜΗ 5: Προσαρμοστικός Simpson
# Ελέγχουμε τη μέθοδο σε τρεις συναρτήσεις, μεταξύ των οποίων η σταθερή
# συνάρτηση f(x)=1 που αποκαλύπτει αμέσως τυχόν λάθος στον συντελεστή κλίμακας.
# --------------------------------------------------------------------------
print("\n[ΔΟΚΙΜΗ 5] Προσαρμοστικός Simpson")
print("-" * 70)

print("α) ∫₀¹ 1 dx = 1")
elegxos("Δοκιμή 5α", SimpsonsRule1D.adaptive(lambda x: 1.0, 0, 1), 1.0, 1e-10)

print("\nβ) ∫₀² x² dx = 8/3")
elegxos("Δοκιμή 5β", SimpsonsRule1D.adaptive(f1, 0, 2), 8/3, 1e-10)

print("\nγ) ∫₀^π sin(x) dx = 2")
elegxos("Δοκιμή 5γ", SimpsonsRule1D.adaptive(f2, 0, np.pi, tol=1e-10), 2.0, 1e-9)

# --------------------------------------------------------------------------
# ΔΟΚΙΜΗ 5δ: ΠΑΘΟΛΟΓΙΚΗ ΠΕΡΙΠΤΩΣΗ — στενή κορυφή ανάμεσα στα αρχικά σημεία
#
# Η f(x) = e^(-10000(x-0.123456)²) είναι πρακτικά μηδενική στα πέντε αρχικά
# σημεία δειγματοληψίας (0, 0.25, 0.5, 0.75, 1). Χωρίς ελάχιστο βάθος
# αναδρομής, το κριτήριο |S₂-S₁| ≤ 15·tol ικανοποιείται ΨΕΥΔΩΣ με S₁=S₂=0
# και η μέθοδος επιστρέφει ~0 αντί για 0.0177 — σφάλμα 100%.
#
# Η παράμετρος min_depth επιβάλλει υποχρεωτικές διαιρέσεις πριν τον έλεγχο.
# Βλ. Gander & Gautschi, "Adaptive Quadrature — Revisited" (2000).
# --------------------------------------------------------------------------
print("\nδ) ΠΑΘΟΛΟΓΙΚΗ: ∫₀¹ e^(-10000(x-0.123456)²) dx  (στενή κορυφή)")

def f_kryfi_koryfi(x):
    return np.exp(-10000 * (x - 0.123456)**2)

# Ακριβής τιμή: η κορυφή είναι εσωτερική και εξαιρετικά στενή, οπότε το
# ολοκλήρωμα ισούται πρακτικά με το πλήρες ολοκλήρωμα Gauss √(π/10000)
akrivis_koryfi = np.sqrt(np.pi / 10000)

# Χωρίς προστασία (min_depth=0) η μέθοδος ΑΠΟΤΥΓΧΑΝΕΙ — το τεκμηριώνουμε
xoris_prostasia = SimpsonsRule1D.adaptive(f_kryfi_koryfi, 0, 1, tol=1e-10, min_depth=0)
print(f"   (χωρίς min_depth: {xoris_prostasia:.3e} — αποτυγχάνει, όπως αναμένεται)")

elegxos("Δοκιμή 5δ", SimpsonsRule1D.adaptive(f_kryfi_koryfi, 0, 1, tol=1e-10),
        akrivis_koryfi, 1e-9)

# --------------------------------------------------------------------------
# ΔΟΚΙΜΗ 6: Κανόνας τραπεζίου και μεσοσημείου
# Και οι δύο έχουν σφάλμα O(h²), οπότε με n=1000 περιμένουμε ~1e-6.
# --------------------------------------------------------------------------
print("\n[ΔΟΚΙΜΗ 6] Τραπέζιο & Μεσοσημείο: ∫₀^π sin(x) dx = 2")
print("-" * 70)

print("α) Κανόνας τραπεζίου (n=1000)")
elegxos("Δοκιμή 6α", TrapezoidalRule.composite(f2, 0, np.pi, n=1000), 2.0, 1e-5)

print("\nβ) Κανόνας μεσοσημείου (n=1000)")
elegxos("Δοκιμή 6β", MidpointRule.composite(f2, 0, np.pi, n=1000), 2.0, 1e-5)

# --------------------------------------------------------------------------
# ΔΟΚΙΜΗ 7: Σύγκριση μεθόδων ΜΕ ΙΣΟ ΚΟΣΤΟΣ σε συνάρτηση Gauss δύο μεταβλητών
#
# Η ακριβής τιμή είναι:
#   ∫∫[-1,1]² e^(-(x²+y²)) dA = (∫[-1,1] e^(-x²) dx)² = (√π · erf(1))²
#
# ΣΗΜΑΝΤΙΚΟ: η σύγκριση γίνεται με το ΙΔΙΟ πλήθος αποτιμήσεων της συνάρτησης.
# Ο Gauss με n=5 κόμβους ανά διεύθυνση χρησιμοποιεί 5×5 = 25 σημεία, οπότε
# τον συγκρίνουμε με Simpson 4×4, που χρησιμοποιεί (4+1)² = 25 σημεία.
# --------------------------------------------------------------------------
print("\n[ΔΟΚΙΜΗ 7] Σύγκριση με ίσο κόστος: ∫∫[-1,1]×[-1,1] e^(-(x²+y²)) dA")
print("-" * 70)

from math import erf

def f7(x, y):
    return np.exp(-(x**2 + y**2))

akrivis_7 = (np.sqrt(np.pi) * erf(1.0))**2

simpson_7 = SimpsonsRule2D.composite(f7, -1, 1, -1, 1, nx=4, ny=4)
gauss_7 = GaussianQuadrature.integrate_2d(f7, -1, 1, -1, 1, n=5)

print(f"Ακριβής τιμή:                    {akrivis_7:.10f}")
print(f"Simpson 2D (4×4 → 25 σημεία):    {simpson_7:.10f}  |  σφάλμα: {abs(simpson_7-akrivis_7):.2e}")
print(f"Gauss 2D   (5×5 → 25 σημεία):    {gauss_7:.10f}  |  σφάλμα: {abs(gauss_7-akrivis_7):.2e}")
print(f"→ Ο Gauss είναι ~{abs(simpson_7-akrivis_7)/abs(gauss_7-akrivis_7):.0f} φορές ακριβέστερος με το ίδιο κόστος.")
elegxos("Δοκιμή 7", gauss_7, akrivis_7, 1e-4)

# --------------------------------------------------------------------------
# Σύνοψη
# --------------------------------------------------------------------------
print("\n" + "=" * 70)
epityxies = sum(apotelesmata)
synolo = len(apotelesmata)
if epityxies == synolo:
    print(f"ΟΛΕΣ ΟΙ ΔΟΚΙΜΕΣ ΠΕΡΑΣΑΝ ΕΠΙΤΥΧΩΣ! ({epityxies}/{synolo})")
else:
    print(f"ΑΠΟΤΥΧΙΑ: πέρασαν {epityxies} από {synolo} δοκιμές.")
print("=" * 70)

sys.exit(0 if epityxies == synolo else 1)
