"""
Υλοποίηση του Κανόνα του Simpson για Αριθμητική Ολοκλήρωση

Ο κανόνας του Simpson είναι μια μέθοδος αριθμητικής ολοκλήρωσης που προσεγγίζει
το ολοκλήρωμα μιας συνάρτησης με πολυώνυμα 2ου βαθμού (παραβολές).

Για μονό ολοκλήρωμα:  ∫[a,b] f(x)dx
Για διπλό ολοκλήρωμα: ∫∫[a,b]×[c,d] f(x,y)dxdy
"""

import numpy as np
from typing import Callable


class SimpsonsRule1D:
    """
    Κανόνας του Simpson για ολοκλήρωση σε μία διάσταση (1D)

    ΙΔΕΑ:
    -----
    Αντί να προσεγγίσουμε το εμβαδόν κάτω από την καμπύλη με ορθογώνια,
    ο κανόνας του Simpson χρησιμοποιεί παραβολές (πολυώνυμα 2ου βαθμού).
    Αυτό βελτιώνει δραματικά την ακρίβεια.

    Το διάστημα [a,b] χωρίζεται σε n ίσα υποδιαστήματα.
    Κάθε ζεύγος διαδοχικών υποδιαστημάτων προσεγγίζεται από μία παραβολή.

    ΤΥΠΟΣ:
    ------
    ∫[a,b] f(x)dx ≈ (h/3) * [f(x₀) + 4f(x₁) + 2f(x₂) + 4f(x₃) + ... + f(xₙ)]

    όπου:
    - h = (b - a) / n   (πλάτος κάθε υποδιαστήματος)
    - x₀, x₁, ..., xₙ είναι τα σημεία διαμέρισης
    - Οι συντελεστές εναλλάσσονται: 1, 4, 2, 4, 2, ..., 4, 1

    ΓΙΑΤΙ ΑΥΤΗ Η ΕΝΑΛΛΑΣΣΟΜΕΝΗ ΔΟΜΗ;
    - Προκύπτει από την παραβολική παρεμβολή ανά ζεύγη υποδιαστημάτων.
    - Ο συντελεστής 4 αντιστοιχεί στους περιττούς δείκτες (τα μέσα των παραβολών).
    - Ο συντελεστής 2 αντιστοιχεί στους άρτιους δείκτες (κοινά άκρα δύο παραβολών),
      εκτός από τα δύο ακραία σημεία που παίρνουν συντελεστή 1.

    ΣΦΑΛΜΑ:
    -------
    ΣΥΜΒΑΣΗ: ορίζουμε E = I - S, δηλαδή (ακριβής τιμή) - (προσέγγιση).
    Αυτή είναι η καθιερωμένη σύμβαση των βιβλίων (π.χ. Burden & Faires).

        E = I - S = -((b-a)/180) * h⁴ * f⁽⁴⁾(ξ)   για κάποιο ξ ∈ (a,b)

    Άρα η μέθοδος είναι τάξης O(h⁴) και ακριβής για πολυώνυμα έως 3ου βαθμού.

    ΤΙ ΜΑΣ ΛΕΕΙ ΤΟ ΠΡΟΣΗΜΟ:
    Αν f⁽⁴⁾ > 0 στο διάστημα, τότε E < 0, δηλαδή I < S: ο Simpson
    ΥΠΕΡΕΚΤΙΜΑ το ολοκλήρωμα. Αν f⁽⁴⁾ < 0, το υποεκτιμά.
    (Επαληθεύτηκε αριθμητικά για f=e^x στο [0,1]: ο λόγος πραγματικού προς
    θεωρητικό σφάλμα τείνει στο 1.000 καθώς n → ∞.)
    """

    @staticmethod
    def simple(f: Callable, a: float, b: float) -> float:
        """
        Απλός κανόνας Simpson: χρησιμοποιεί ΜΙΑ μόνο παραβολή για όλο το διάστημα.
        Κατάλληλος για γρήγορες εκτιμήσεις, αλλά λιγότερο ακριβής.

        Τύπος: (b-a)/6 * [f(a) + 4f((a+b)/2) + f(b)]

        Ορίσματα:
            f: Η συνάρτηση προς ολοκλήρωση
            a: Αριστερό άκρο
            b: Δεξί άκρο

        Επιστρέφει:
            Προσεγγιστική τιμή του ολοκληρώματος
        """
        # h είναι το μισό του διαστήματος, οπότε h/3 = (b-a)/6
        h = (b - a) / 2
        midpoint = (a + b) / 2
        result = (h / 3) * (f(a) + 4 * f(midpoint) + f(b))
        return result

    @staticmethod
    def composite(f: Callable, a: float, b: float, n: int = 100) -> float:
        """
        Σύνθετος κανόνας Simpson: χωρίζει το διάστημα σε n υποδιαστήματα
        και εφαρμόζει τον κανόνα του Simpson σε κάθε ζεύγος υποδιαστημάτων.

        ΠΡΟΣΟΧΗ: το n πρέπει να είναι ΑΡΤΙΟΣ αριθμός!
        (Αν δοθεί περιττό, αυξάνεται αυτόματα κατά 1.)

        Ορίσματα:
            f: Η συνάρτηση προς ολοκλήρωση
            a: Αριστερό άκρο
            b: Δεξί άκρο
            n: Πλήθος υποδιαστημάτων (γίνεται άρτιο). Όσο μεγαλύτερο, τόσο ακριβέστερο

        Επιστρέφει:
            Προσεγγιστική τιμή του ολοκληρώματος
        """
        # Έλεγχος εγκυρότητας: χρειαζόμαστε τουλάχιστον ένα ζεύγος υποδιαστημάτων
        if n < 2:
            raise ValueError(f"Το n πρέπει να είναι τουλάχιστον 2, δόθηκε n={n}")

        # Εξασφαλίζουμε ότι το n είναι άρτιο (απαίτηση της μεθόδου)
        if n % 2 != 0:
            n += 1

        # Υπολογισμός του πλάτους κάθε υποδιαστήματος
        h = (b - a) / n

        # Δημιουργία όλων των σημείων: x₀, x₁, x₂, ..., xₙ
        x = np.linspace(a, b, n + 1)

        # Υπολογισμός των τιμών f(x) σε όλα τα σημεία
        y = np.array([f(xi) for xi in x])

        # Εφαρμογή του τύπου με τους εναλλασσόμενους συντελεστές
        # Ξεκινάμε με τον πρώτο όρο: 1 * f(x₀)
        result = y[0]

        # Ενδιάμεσοι όροι με εναλλασσόμενους συντελεστές (4, 2, 4, 2, ...)
        result += 4 * np.sum(y[1:-1:2])  # y[1], y[3], y[5], ... → συντελεστής 4
        result += 2 * np.sum(y[2:-1:2])  # y[2], y[4], y[6], ... → συντελεστής 2

        # Τελευταίος όρος: 1 * f(xₙ)
        result += y[-1]

        # Πολλαπλασιασμός με h/3
        result *= (h / 3)

        return result

    @staticmethod
    def adaptive(f: Callable, a: float, b: float, tol: float = 1e-6,
                 max_depth: int = 50, min_depth: int = 4) -> float:
        """
        Προσαρμοστικός κανόνας Simpson: εκλεπτύνει αυτόματα τη διαμέριση
        στις περιοχές όπου η συνάρτηση μεταβάλλεται απότομα.

        Αντί για σταθερό πλήθος υποδιαστημάτων, η μέθοδος διαιρεί αναδρομικά
        κάθε διάστημα στη μέση μέχρι η προσέγγιση να είναι αρκετά καλή (εντός ανοχής).

        ΚΡΙΤΗΡΙΟ ΣΥΓΚΛΙΣΗΣ:
        Αν S₁ είναι ο απλός Simpson σε όλο το διάστημα [a,b] και
        S₂ = S(a,c) + S(c,b) ο Simpson στα δύο μισά, τότε το σφάλμα
        εκτιμάται ως |S₂ - S₁| / 15 (επειδή το σφάλμα είναι O(h⁴) και το h
        υποδιπλασιάζεται → ο παράγοντας είναι 2⁴ - 1 = 15).
        Δεχόμαστε το αποτέλεσμα όταν |S₂ - S₁| ≤ 15·tol και εφαρμόζουμε
        την εξτραπόλαση Richardson: S₂ + (S₂ - S₁)/15.

        ΑΠΟΔΟΤΙΚΟΤΗΤΑ:
        Οι ήδη υπολογισμένες τιμές f(a), f(m), f(b) περνούν ως ορίσματα στα
        αναδρομικά βήματα. Έτσι κάθε επίπεδο αναδρομής κοστίζει μόλις ΔΥΟ νέες
        αποτιμήσεις της f αντί για έξι — δηλαδή τρεις φορές λιγότερες κλήσεις.
        Αυτό είναι κρίσιμο όταν η αποτίμηση της f είναι ακριβή υπολογιστικά.

        ΓΙΑΤΙ ΧΡΕΙΑΖΕΤΑΙ ΤΟ min_depth (ΣΗΜΑΝΤΙΚΟ):
        Το κριτήριο σύγκλισης είναι ΤΟΠΙΚΟ: κοιτάζει μόνο 5 σημεία. Αν η
        συνάρτηση έχει στενή κορυφή που «χωράει» ανάμεσα σε αυτά τα σημεία,
        τότε και οι δύο εκτιμήσεις S₁, S₂ βγαίνουν ίσες (π.χ. μηδέν), το
        κριτήριο ικανοποιείται ψευδώς και η αναδρομή σταματά αμέσως,
        επιστρέφοντας τελείως λάθος αποτέλεσμα.

        Παράδειγμα αποτυχίας: η f(x) = e^(-10000(x-0.123456)²) στο [0,1]
        είναι πρακτικά μηδενική στα σημεία 0, 0.25, 0.5, 0.75, 1. Χωρίς
        ελάχιστο βάθος, η μέθοδος επιστρέφει ~0 αντί για 0.0177.

        Η λύση είναι να επιβάλουμε min_depth υποχρεωτικές διαιρέσεις ΠΡΙΝ
        επιτραπεί ο έλεγχος τερματισμού: με min_depth=4 εξετάζουμε 2⁴ = 16
        υποδιαστήματα (65 σημεία) πριν εμπιστευτούμε το κριτήριο.
        Τη σημασία του κριτηρίου τερματισμού στους αναδρομικούς αλγορίθμους
        τονίζουν οι Gander & Gautschi, "Adaptive Quadrature — Revisited" (2000).
        ΚΟΣΤΟΣ: τουλάχιστον 65 αποτιμήσεις ακόμη και για εύκολες συναρτήσεις·
        σε αυστηρές ανοχές (~1e-10) η επιβάρυνση πρακτικά μηδενίζεται.
        ΣΗΜΕΙΩΣΗ: κανένας προσαρμοστικός αλγόριθμος δεν εξαλείφει πλήρως αυτόν
        τον κίνδυνο· το min_depth τον μειώνει δραστικά, δεν τον μηδενίζει.

        Ορίσματα:
            f: Η συνάρτηση προς ολοκλήρωση
            a: Αριστερό άκρο
            b: Δεξί άκρο
            tol: Ανοχή (πόσο ακριβές θέλουμε το αποτέλεσμα)
            max_depth: Μέγιστο βάθος αναδρομής, για αποφυγή ατέρμονης διαίρεσης
            min_depth: Ελάχιστο βάθος υποχρεωτικής διαίρεσης (βλ. παραπάνω)

        Επιστρέφει:
            Προσεγγιστική τιμή του ολοκληρώματος εντός της δοσμένης ανοχής
        """

        def adaptive_helper(a, m, b, fa, fm, fb, whole, tol, depth):
            """
            Αναδρομική βοηθητική συνάρτηση.

            a, m, b   : αριστερό άκρο, μέσο, δεξί άκρο
            fa, fm, fb: οι ΗΔΗ υπολογισμένες τιμές της f σε αυτά τα σημεία
            whole     : ο απλός Simpson στο [a,b], υπολογισμένος από τον καλούντα
            """
            # Τα μέσα του αριστερού και του δεξιού μισού — τα ΜΟΝΑ δύο
            # σημεία στα οποία χρειάζεται να αποτιμήσουμε ξανά τη συνάρτηση
            lm = (a + m) / 2
            rm = (m + b) / 2
            flm = f(lm)
            frm = f(rm)

            # Simpson στο αριστερό και στο δεξί μισό
            left = ((m - a) / 6) * (fa + 4 * flm + fm)
            right = ((b - m) / 6) * (fm + 4 * frm + fb)

            # Εκτίμηση σφάλματος κατά Richardson
            delta = left + right - whole

            # Έλεγχος αν έχουμε φτάσει την επιθυμητή ακρίβεια.
            # Το κριτήριο ενεργοποιείται ΜΟΝΟ αφού έχουμε ξεπεράσει το
            # ελάχιστο βάθος, ώστε να μην ξεγελαστούμε από στενές κορυφές.
            if depth >= max_depth or (depth >= min_depth and abs(delta) <= 15 * tol):
                return left + right + delta / 15

            # Διαφορετικά, συνεχίζουμε αναδρομικά σε κάθε μισό με τη μισή ανοχή,
            # ώστε το άθροισμα των δύο σφαλμάτων να παραμείνει κάτω από tol
            return (adaptive_helper(a, lm, m, fa, flm, fm, left, tol / 2, depth + 1) +
                    adaptive_helper(m, rm, b, fm, frm, fb, right, tol / 2, depth + 1))

        # Αρχική εκτίμηση με απλό Simpson σε ολόκληρο το διάστημα [a,b]
        m = (a + b) / 2
        fa, fm, fb = f(a), f(m), f(b)
        whole = ((b - a) / 6) * (fa + 4 * fm + fb)

        return adaptive_helper(a, m, b, fa, fm, fb, whole, tol, 0)


class SimpsonsRule2D:
    """
    Κανόνας του Simpson για διπλά ολοκληρώματα (2D)

    ΙΔΕΑ:
    -----
    Για να ολοκληρώσουμε μια συνάρτηση δύο μεταβλητών f(x,y) πάνω σε ένα
    ορθογώνιο χωρίο [a,b]×[c,d], εφαρμόζουμε τον κανόνα του Simpson δύο φορές:
    1. Πρώτα κατά τη διεύθυνση y (εσωτερικό ολοκλήρωμα)
    2. Έπειτα κατά τη διεύθυνση x (εξωτερικό ολοκλήρωμα)

    Αυτό ονομάζεται "σύνθετος κανόνας Simpson σε 2 διαστάσεις" ή
    "κανόνας Simpson πάνω σε πλέγμα (grid)".

    ΤΥΠΟΣ:
    ------
    ∫∫[a,b]×[c,d] f(x,y)dydx ≈ (hₓ/3)(h_y/3) * Σᵢ Σⱼ cᵢ · cⱼ · f(xᵢ, yⱼ)

    όπου cᵢ, cⱼ είναι οι συντελεστές 1, 4, 2, 4, ..., 2, 4, 1 σε κάθε διεύθυνση.
    Το συνολικό σφάλμα είναι O(hₓ⁴) + O(h_y⁴).
    """

    @staticmethod
    def composite(f: Callable[[float, float], float],
                  a: float, b: float,
                  c: float, d: float,
                  nx: int = 50, ny: int = 50) -> float:
        """
        Σύνθετος κανόνας Simpson για ολοκλήρωση σε δύο διαστάσεις.

        Ορίσματα:
            f: Η συνάρτηση f(x, y) προς ολοκλήρωση
            a, b: Όρια ως προς x
            c, d: Όρια ως προς y
            nx: Πλήθος υποδιαστημάτων κατά x (γίνεται άρτιο)
            ny: Πλήθος υποδιαστημάτων κατά y (γίνεται άρτιο)

        Επιστρέφει:
            Προσεγγιστική τιμή του διπλού ολοκληρώματος
        """
        # Έλεγχος εγκυρότητας και στις δύο διαστάσεις
        if nx < 2 or ny < 2:
            raise ValueError(f"Τα nx, ny πρέπει να είναι τουλάχιστον 2, δόθηκαν nx={nx}, ny={ny}")

        # Και οι δύο διαστάσεις πρέπει να έχουν άρτιο πλήθος υποδιαστημάτων
        if nx % 2 != 0:
            nx += 1
        if ny % 2 != 0:
            ny += 1

        # Υπολογισμός του βήματος του πλέγματος σε κάθε διεύθυνση
        hx = (b - a) / nx
        hy = (d - c) / ny

        # Δημιουργία του πλέγματος
        x = np.linspace(a, b, nx + 1)
        y = np.linspace(c, d, ny + 1)

        # Πίνακας τιμών της συνάρτησης: F[i,j] = f(x[i], y[j])
        F = np.zeros((nx + 1, ny + 1))
        for i in range(nx + 1):
            for j in range(ny + 1):
                F[i, j] = f(x[i], y[j])

        # Εφαρμογή του κανόνα Simpson και στις δύο διαστάσεις
        result = 0
        for i in range(nx + 1):
            # Για κάθε θέση x, ολοκληρώνουμε κατά y με τον κανόνα Simpson
            y_integral = (F[i, 0] +
                          4 * np.sum(F[i, 1:-1:2]) +   # περιττοί δείκτες → συντελεστής 4
                          2 * np.sum(F[i, 2:-1:2]) +   # άρτιοι δείκτες → συντελεστής 2
                          F[i, -1])
            y_integral *= (hy / 3)

            # Εφαρμογή των συντελεστών Simpson κατά τη διεύθυνση x
            if i == 0 or i == nx:
                result += y_integral       # Πρώτο και τελευταίο σημείο → συντελεστής 1
            elif i % 2 == 1:
                result += 4 * y_integral   # Περιττοί δείκτες → συντελεστής 4
            else:
                result += 2 * y_integral   # Άρτιοι δείκτες → συντελεστής 2

        result *= (hx / 3)

        return result
