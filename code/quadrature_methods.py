"""
Μέθοδοι Αριθμητικής Ολοκλήρωσης (Quadrature)

Ο όρος "quadrature" (τετραγωνισμός) είναι η παραδοσιακή ονομασία της αριθμητικής
ολοκλήρωσης. Προέρχεται από το αρχαίο πρόβλημα του τετραγωνισμού του κύκλου,
δηλαδή της εύρεσης τετραγώνου με εμβαδόν ίσο με αυτό ενός δοσμένου σχήματος.

Το module αυτό περιλαμβάνει:
1. Gaussian Quadrature (πολύ ακριβής, χρησιμοποιεί ειδικούς κόμβους και βάρη)
2. Κανόνα Τραπεζίου (απλός αλλά λιγότερο ακριβής)
3. Κανόνα Μεσοσημείου
"""

import numpy as np
from typing import Callable


class GaussianQuadrature:
    """
    Μέθοδος Ολοκλήρωσης Gauss (Gaussian Quadrature)

    ΙΔΕΑ:
    -----
    Η ολοκλήρωση Gauss είναι ένα σταθμισμένο άθροισμα τιμών της συνάρτησης
    σε συγκεκριμένα σημεία:

    ∫[a,b] f(x)dx ≈ Σ wᵢ * f(xᵢ)

    όπου:
    - xᵢ ονομάζονται "κόμβοι" (nodes ή abscissas) — ειδικά επιλεγμένα σημεία
    - wᵢ ονομάζονται "βάρη" (weights) — ειδικά υπολογισμένοι συντελεστές

    ΓΙΑΤΙ ΕΙΝΑΙ ΞΕΧΩΡΙΣΤΗ;
    - Αντί να αποτιμούμε την f σε ισαπέχοντα σημεία, χρησιμοποιούμε σημεία
      που έχουν επιλεγεί με βέλτιστο τρόπο.
    - Κόμβοι και βάρη σχεδιάζονται ώστε να δίνουν ΑΚΡΙΒΕΣ αποτέλεσμα για πολυώνυμα.
    - Με n κόμβους η μέθοδος είναι ακριβής για πολυώνυμα βαθμού έως 2n-1!
      (Έχουμε 2n ελεύθερες παραμέτρους: n κόμβοι + n βάρη.)

    ΑΠΟ ΠΟΥ ΠΡΟΕΡΧΟΝΤΑΙ ΟΙ ΚΟΜΒΟΙ ΚΑΙ ΤΑ ΒΑΡΗ;
    - Οι κόμβοι είναι οι ρίζες των πολυωνύμων Legendre Pₙ(x).
    - Τα πολυώνυμα Legendre είναι ορθογώνια στο [-1,1] ως προς το εσωτερικό
      γινόμενο ⟨f,g⟩ = ∫[-1,1] f(x)g(x)dx.
    - Τα βάρη υπολογίζονται από τον τύπο wᵢ = 2 / [(1-xᵢ²)·(P'ₙ(xᵢ))²].

    ΤΥΠΙΚΟ ΔΙΑΣΤΗΜΑ:
    - Η μέθοδος ορίζεται στο [-1, 1].
    - Για οποιοδήποτε άλλο διάστημα [a, b] χρησιμοποιούμε αλλαγή μεταβλητής
      (βλ. τη μέθοδο integrate παρακάτω).
    """

    # Προϋπολογισμένοι κόμβοι και βάρη Gauss-Legendre για τάξεις n = 1...5.
    # Μορφή: {n: ([κόμβοι], [βάρη])}
    #
    # ΓΙΑΤΙ ΣΤΑΜΑΤΑΜΕ ΣΤΟ n=5 (συνειδητή επιλογή, όχι παράλειψη):
    # Μέχρι το n=5 οι ρίζες των πολυωνύμων Legendre έχουν ΑΠΛΗ ΚΛΕΙΣΤΗ ΜΟΡΦΗ:
    # το P_n έχει μόνο άρτιες ή μόνο περιττές δυνάμεις του x, οπότε με u = x²
    # ανάγεται σε δευτεροβάθμια εξίσωση — οι τιμές γράφονται και επαληθεύονται
    # με το χέρι. Για μεγαλύτερα n οι κλειστοί τύποι γίνονται γρήγορα
    # δυσχείριστοι, οπότε στην πράξη οι ρίζες υπολογίζονται αριθμητικά,
    # π.χ. με Newton-Raphson ή ως ιδιοτιμές του τριδιαγώνιου πίνακα Jacobi
    # (αλγόριθμος Golub-Welsch, που χρησιμοποιεί η SciPy).
    # Επειδή ο σκοπός εδώ είναι η ΚΑΤΑΝΟΗΣΗ της μεθόδου, κρατάμε τις τιμές
    # που μπορούν να ελεγχθούν αναλυτικά.
    #
    # ΕΠΑΛΗΘΕΥΣΗ: όλες οι παρακάτω τιμές έχουν συγκριθεί με τη
    # scipy.special.roots_legendre (Golub-Welsch) και συμφωνούν στα ~1e-16.
    # Βλ. verify_against_scipy.py, ενότητα 1.
    GAUSS_LEGENDRE_TABLE = {
        1: (np.array([0.0]),
            np.array([2.0])),

        2: (np.array([-1.0/np.sqrt(3), 1.0/np.sqrt(3)]),
            np.array([1.0, 1.0])),

        3: (np.array([-np.sqrt(3.0/5), 0.0, np.sqrt(3.0/5)]),
            np.array([5.0/9, 8.0/9, 5.0/9])),

        4: (np.array([-np.sqrt((3 + 2*np.sqrt(6.0/5))/7),
                      -np.sqrt((3 - 2*np.sqrt(6.0/5))/7),
                       np.sqrt((3 - 2*np.sqrt(6.0/5))/7),
                       np.sqrt((3 + 2*np.sqrt(6.0/5))/7)]),
            np.array([(18 - np.sqrt(30))/36,
                      (18 + np.sqrt(30))/36,
                      (18 + np.sqrt(30))/36,
                      (18 - np.sqrt(30))/36])),

        5: (np.array([-np.sqrt(5 + 2*np.sqrt(10.0/7))/3,
                      -np.sqrt(5 - 2*np.sqrt(10.0/7))/3,
                       0.0,
                       np.sqrt(5 - 2*np.sqrt(10.0/7))/3,
                       np.sqrt(5 + 2*np.sqrt(10.0/7))/3]),
            np.array([(322 - 13*np.sqrt(70))/900,
                      (322 + 13*np.sqrt(70))/900,
                      128.0/225,
                      (322 + 13*np.sqrt(70))/900,
                      (322 - 13*np.sqrt(70))/900]))
    }

    @staticmethod
    def integrate_standard(f: Callable, n: int = 5) -> float:
        """
        Ολοκλήρωση Gauss στο τυπικό διάστημα [-1, 1].

        Τύπος: ∫[-1,1] f(x)dx ≈ Σ wᵢ * f(xᵢ)

        Ορίσματα:
            f: Η συνάρτηση προς ολοκλήρωση
            n: Πλήθος κόμβων (1, 2, 3, 4 ή 5). Περισσότεροι κόμβοι → μεγαλύτερος
               βαθμός ακρίβειας (ακριβής για πολυώνυμα βαθμού έως 2n-1)

        Επιστρέφει:
            Προσεγγιστική τιμή του ολοκληρώματος
        """
        if n not in GaussianQuadrature.GAUSS_LEGENDRE_TABLE:
            raise ValueError(f"Υποστηριζόμενες τιμές για n: {list(GaussianQuadrature.GAUSS_LEGENDRE_TABLE.keys())}")

        nodes, weights = GaussianQuadrature.GAUSS_LEGENDRE_TABLE[n]

        # Απλό σταθμισμένο άθροισμα: Σ wᵢ * f(xᵢ)
        result = np.sum(weights * np.array([f(x) for x in nodes]))
        return result

    @staticmethod
    def integrate(f: Callable, a: float, b: float, n: int = 5) -> float:
        """
        Ολοκλήρωση Gauss σε τυχαίο διάστημα [a, b].

        ΑΛΛΑΓΗ ΜΕΤΑΒΛΗΤΗΣ:
        Για να μεταφερθούμε από το [-1, 1] στο [a, b] χρησιμοποιούμε:

            x = ((b-a)/2) * t + (a+b)/2,   dx = ((b-a)/2) dt

        όπου t ∈ [-1, 1] και x ∈ [a, b].

        Το ολοκλήρωμα γίνεται:

            ∫[a,b] f(x)dx = ((b-a)/2) * ∫[-1,1] f(x(t)) dt ≈ ((b-a)/2) * Σ wᵢ f(x(tᵢ))

        Ο παράγοντας (b-a)/2 είναι η Ιακωβιανή του μετασχηματισμού.

        Ορίσματα:
            f: Η συνάρτηση προς ολοκλήρωση
            a: Αριστερό άκρο
            b: Δεξί άκρο
            n: Πλήθος κόμβων (1, 2, 3, 4 ή 5)

        Επιστρέφει:
            Προσεγγιστική τιμή του ολοκληρώματος
        """
        if n not in GaussianQuadrature.GAUSS_LEGENDRE_TABLE:
            raise ValueError(f"Υποστηριζόμενες τιμές για n: {list(GaussianQuadrature.GAUSS_LEGENDRE_TABLE.keys())}")

        nodes, weights = GaussianQuadrature.GAUSS_LEGENDRE_TABLE[n]

        # Μετασχηματισμός των κόμβων από το [-1, 1] στο [a, b]
        x_transformed = ((b - a) / 2) * nodes + (a + b) / 2

        # Αποτίμηση της συνάρτησης στους μετασχηματισμένους κόμβους
        f_values = np.array([f(x) for x in x_transformed])

        # Πολλαπλασιασμός των βαρών με την Ιακωβιανή (b-a)/2
        scaled_weights = weights * ((b - a) / 2)

        # Υπολογισμός του σταθμισμένου αθροίσματος
        result = np.sum(scaled_weights * f_values)
        return result

    @staticmethod
    def integrate_2d(f: Callable[[float, float], float],
                     a: float, b: float,
                     c: float, d: float,
                     n: int = 5) -> float:
        """
        Ολοκλήρωση Gauss για διπλά ολοκληρώματα (2D).

        ΤΥΠΟΣ:
        ∫∫[a,b]×[c,d] f(x,y)dydx ≈ Σᵢ Σⱼ wᵢ * wⱼ * f(xᵢ, yⱼ)

        Πρόκειται για "τανυστικό γινόμενο" (tensor product) του μονοδιάστατου
        κανόνα: εφαρμόζουμε τους ίδιους κόμβους/βάρη ανεξάρτητα σε κάθε διεύθυνση.
        Με n κόμβους ανά διεύθυνση χρειάζονται μόνο n² αποτιμήσεις της f.

        Ορίσματα:
            f: Η συνάρτηση f(x, y) προς ολοκλήρωση
            a, b: Όρια ως προς x
            c, d: Όρια ως προς y
            n: Πλήθος κόμβων ανά διεύθυνση (1, 2, 3, 4 ή 5)

        Επιστρέφει:
            Προσεγγιστική τιμή του διπλού ολοκληρώματος
        """
        if n not in GaussianQuadrature.GAUSS_LEGENDRE_TABLE:
            raise ValueError(f"Υποστηριζόμενες τιμές για n: {list(GaussianQuadrature.GAUSS_LEGENDRE_TABLE.keys())}")

        nodes_x, weights_x = GaussianQuadrature.GAUSS_LEGENDRE_TABLE[n]
        nodes_y, weights_y = GaussianQuadrature.GAUSS_LEGENDRE_TABLE[n]

        # Μετασχηματισμός των κόμβων σε κάθε διεύθυνση
        x_transformed = ((b - a) / 2) * nodes_x + (a + b) / 2
        y_transformed = ((d - c) / 2) * nodes_y + (c + d) / 2

        # Κλιμάκωση των βαρών με την αντίστοιχη Ιακωβιανή
        scaled_weights_x = weights_x * ((b - a) / 2)
        scaled_weights_y = weights_y * ((d - c) / 2)

        # Υπολογισμός του διπλού αθροίσματος
        result = 0.0
        for i in range(len(x_transformed)):
            for j in range(len(y_transformed)):
                result += scaled_weights_x[i] * scaled_weights_y[j] * f(x_transformed[i], y_transformed[j])

        return result


class TrapezoidalRule:
    """
    Κανόνας του Τραπεζίου (Trapezoidal Rule)

    ΙΔΕΑ:
    -----
    Αντί για ορθογώνια ή παραβολές, χρησιμοποιούμε τραπέζια!

    Το διάστημα [a,b] χωρίζεται σε n υποδιαστήματα. Πάνω από κάθε υποδιάστημα
    σχεδιάζουμε ένα τραπέζιο που ενώνει τα σημεία f(xᵢ) και f(xᵢ₊₁) με ευθεία.

    Εμβαδόν τραπεζίου = (πλάτος) * (ύψος₁ + ύψος₂) / 2

    ΤΥΠΟΣ:
    ∫[a,b] f(x)dx ≈ (h/2) * [f(x₀) + 2f(x₁) + 2f(x₂) + ... + 2f(xₙ₋₁) + f(xₙ)]

    όπου h = (b - a) / n

    ΑΚΡΙΒΕΙΑ:
    - Λιγότερο ακριβής από τον κανόνα Simpson (που χρησιμοποιεί παραβολές)
    - Αλλά απλούστερος στην υλοποίηση
    - Ακριβής για πολυώνυμα μέχρι 1ου βαθμού

    ΣΥΜΒΑΣΗ ΣΦΑΛΜΑΤΟΣ: E = I - S, δηλαδή (ακριβής τιμή) - (προσέγγιση).

        E = I - S = -((b-a)/12) * h² * f''(ξ)   →  τάξης O(h²)

    ΤΙ ΜΑΣ ΛΕΕΙ ΤΟ ΠΡΟΣΗΜΟ:
    Αν f'' > 0 (κυρτή συνάρτηση), τότε E < 0, δηλαδή I < S: ο κανόνας
    ΥΠΕΡΕΚΤΙΜΑ. Αυτό είναι γεωμετρικά προφανές — η χορδή του τραπεζίου
    βρίσκεται ΠΑΝΩ από μια κυρτή καμπύλη.
    """

    @staticmethod
    def composite(f: Callable, a: float, b: float, n: int = 100) -> float:
        """
        Σύνθετος κανόνας τραπεζίου

        Ορίσματα:
            f: Η συνάρτηση προς ολοκλήρωση
            a: Αριστερό άκρο
            b: Δεξί άκρο
            n: Πλήθος υποδιαστημάτων

        Επιστρέφει:
            Προσεγγιστική τιμή του ολοκληρώματος
        """
        if n < 1:
            raise ValueError(f"Το n πρέπει να είναι τουλάχιστον 1, δόθηκε n={n}")

        h = (b - a) / n

        # Δημιουργία των σημείων του πλέγματος
        x = np.linspace(a, b, n + 1)
        y = np.array([f(xi) for xi in x])

        # Εφαρμογή του τύπου: τα ακραία σημεία με συντελεστή 1,
        # τα ενδιάμεσα με συντελεστή 2 (έχουμε βγάλει κοινό παράγοντα το h)
        result = (y[0] + y[-1]) / 2 + np.sum(y[1:-1])
        result *= h

        return result


class MidpointRule:
    """
    Κανόνας του Μεσοσημείου (Midpoint Rule)

    ΙΔΕΑ:
    -----
    Η απλούστερη μέθοδος αριθμητικής ολοκλήρωσης.
    Χωρίζουμε το διάστημα σε n ορθογώνια και χρησιμοποιούμε το μέσο κάθε
    υποδιαστήματος για να καθορίσουμε το ύψος του ορθογωνίου.

    ΤΥΠΟΣ:
    ∫[a,b] f(x)dx ≈ h * Σ f(xᵢ₊₁/₂)

    όπου:
    - h = (b - a) / n
    - xᵢ₊₁/₂ είναι το μέσο του i-οστού υποδιαστήματος

    ΑΚΡΙΒΕΙΑ:
    - Λιγότερο ακριβής από τον κανόνα Simpson

    ΣΥΜΒΑΣΗ ΣΦΑΛΜΑΤΟΣ: E = I - S, δηλαδή (ακριβής τιμή) - (προσέγγιση).

        E = I - S = +((b-a)/24) * h² * f''(ξ)   →  τάξης O(h²)

    ΤΙ ΜΑΣ ΛΕΕΙ ΤΟ ΠΡΟΣΗΜΟ:
    Το πρόσημο είναι ΑΝΤΙΘΕΤΟ από του τραπεζίου. Αν f'' > 0 (κυρτή), τότε
    E > 0, δηλαδή I > S: ο κανόνας ΥΠΟΕΚΤΙΜΑ — ενώ το τραπέζιο υπερεκτιμά.
    Η πραγματική τιμή βρίσκεται πάντα ΑΝΑΜΕΣΑ στις δύο εκτιμήσεις.

    - ΠΡΟΣΟΧΗ: αν και έχει την ίδια τάξη με τον κανόνα τραπεζίου, η σταθερά
      του σφάλματος είναι 1/24 έναντι 1/12. Δηλαδή ο κανόνας μεσοσημείου είναι
      περίπου ΔΥΟ ΦΟΡΕΣ ΑΚΡΙΒΕΣΤΕΡΟΣ από τον κανόνα τραπεζίου, και μάλιστα με
      μία αποτίμηση λιγότερη (n αντί για n+1). Επιπλέον τα σφάλματα των δύο
      μεθόδων έχουν αντίθετο πρόσημο — από αυτό ακριβώς προκύπτει ο κανόνας
      Simpson: (2·Μεσοσημείο_n + Τραπέζιο_n)/3 = Simpson με 2n υποδιαστήματα.
    - Πλεονέκτημα: δεν αποτιμά τη συνάρτηση στα άκρα, οπότε είναι χρήσιμος
      για ολοκληρώματα με ανωμαλία (singularity) στα άκρα.
    """

    @staticmethod
    def composite(f: Callable, a: float, b: float, n: int = 100) -> float:
        """
        Σύνθετος κανόνας μεσοσημείου

        Ορίσματα:
            f: Η συνάρτηση προς ολοκλήρωση
            a: Αριστερό άκρο
            b: Δεξί άκρο
            n: Πλήθος υποδιαστημάτων

        Επιστρέφει:
            Προσεγγιστική τιμή του ολοκληρώματος
        """
        if n < 1:
            raise ValueError(f"Το n πρέπει να είναι τουλάχιστον 1, δόθηκε n={n}")

        h = (b - a) / n

        # Δημιουργία των σημείων του πλέγματος (n+1 άκρα → n υποδιαστήματα)
        x = np.linspace(a, b, n + 1)

        # Υπολογισμός των μέσων κάθε υποδιαστήματος
        midpoints = (x[:-1] + x[1:]) / 2

        # Αποτίμηση της συνάρτησης στα μέσα και άθροιση
        result = h * np.sum(np.array([f(m) for m in midpoints]))

        return result
